# The one and only content type Excel mode ever writes; anything else at the resolved path/ids
# target is a user configuration error (design spec §6 "non-XLSX workbook target").
XLSX_MIME_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"

# `$select` used for every workbook-item lookup (ids mode, every path form, the sharing-link
# driveItem) — just enough to identify the item, check its mime type, and (for creation) know
# where it lives.
WORKBOOK_ITEM_SELECT = "id,name,file,parentReference"

# `$select` used when listing worksheets (`resolve_worksheet`) — `visibility` isn't consumed in
# this module, but is needed by plan Task 8's `getWorksheets` sync action (v1-parity output
# includes hidden sheets with a `" (hidden)"` title suffix).
WORKSHEET_LIST_SELECT = "id,name,position,visibility"

# How often to poll the `Location` header of a 202 `createSession` response (design spec §4:
# "`202`/`Location` polling").
_SESSION_POLL_INTERVAL_SECONDS = 2.0

# Deadline for `_poll_session_creation`: `_SESSION_POLL_MAX_ATTEMPTS * _SESSION_POLL_INTERVAL_SECONDS`
# ~= 120s. A session that's still "running" past this point falls back to sessionless (same as any
# other session-creation failure) rather than polling forever.
_SESSION_POLL_MAX_ATTEMPTS = 60

# Bundled minimal-XLSX fixture (generated by `tests/setup/generate_empty_workbook_fixture.py`),
# loaded via `importlib.resources` so the runtime image never needs `openpyxl` installed (it's a
# dev-only dependency — see `pyproject.toml`).
_EMPTY_WORKBOOK_PACKAGE = "client.fixtures"
_EMPTY_WORKBOOK_RESOURCE_NAME = "empty.xlsx"

# v1's `workbook.path` forms, matched in this order in `_resolve_by_path`: an `https://` sharing
# link and the `drive://`/`site://` forms each have a distinct, unambiguous prefix; the plain
# root-relative form is "starts with a single `/`" and is checked last so it never shadows the
# others. Anything matching none of these four is `InvalidWorkbookPathError` ("unexpected path
# format").
_SHARING_LINK_RE = re.compile(r"^https://", re.IGNORECASE)
_DRIVE_PATH_RE = re.compile(r"^drive://([^/]+)/(.+)$")
_SITE_PATH_RE = re.compile(r"^site://([^/]+)/(.+)$")
_ROOT_PATH_RE = re.compile(r"^/(.+)$")

# A single spreadsheet cell address, e.g. "C9" -> column "C", row 9.
_CELL_ADDRESS_RE = re.compile(r"^([A-Za-z]+)(\d+)$")

# `write_mode='upsert'` guardrail: above this many cells in the existing used range, refuse the
# combined `usedRange` read up front rather than attempting it — well below Graph's own hard
# 5,000,000-cell read limit, but already impractical to hold in memory and diff row-by-row for a
# component that's meant to run unattended. 'overwrite'/'append' never read the existing sheet's
# values at all, so they remain the escape hatch a oversized-sheet row should fall back to.
_UPSERT_MAX_EXISTING_CELLS = 500_000

# Joins composite key column values into one lookup string (`_build_key_columns_index`). A NUL
# byte never appears in a CSV cell value, so this can't collide with a genuine multi-column key
# that happens to contain the separator itself.
_KEY_SEPARATOR = "\x00"


# ---------------------------------------------------------------------------------------------
# Column / range address math
# ---------------------------------------------------------------------------------------------


def column_int_to_str(column: int) -> str:
    """Convert a 1-based column number to its spreadsheet letter(s): 1 -> "A", 27 -> "AA"."""
    if column < 1:
        raise ValueError(f"Column number must be >= 1, got {column}.")
    letters = ""
    while column > 0:
        column, remainder = divmod(column - 1, 26)
        letters = chr(ord("A") + remainder) + letters
    return letters


def column_str_to_int(column: str) -> int:
    """Convert spreadsheet column letter(s) to a 1-based column number: "A" -> 1, "AA" -> 27."""
    if not column or not column.isalpha():
        raise ValueError(f"Invalid column letters: {column!r}.")
    result = 0
    for char in column.upper():
        result = result * 26 + (ord(char) - ord("A") + 1)
    return result


@dataclass(frozen=True)
class RangeAddress:
    """A parsed Excel range address, e.g. "Sheet1!C9:F20" -> sheet="Sheet1", C9..F20."""

    sheet: str
    start_col: int
    start_row: int
    end_col: int
    end_row: int


def parse_range_address(address: str) -> RangeAddress:
    """Parse a Graph range ``address`` string (``"Sheet1!C9:F20"`` or a bare ``"A1:A1"``)."""
    sheet, _, cells = address.partition("!")
    if not cells:
        sheet, cells = "", sheet
    start_cell, separator, end_cell = cells.partition(":")
    if not separator:
        end_cell = start_cell

    start_match = _CELL_ADDRESS_RE.match(start_cell)
    end_match = _CELL_ADDRESS_RE.match(end_cell)
    if not start_match or not end_match:
        raise ValueError(f"Cannot parse range address {address!r}.")

    return RangeAddress(
        sheet=sheet,
        start_col=column_str_to_int(start_match.group(1)),
        start_row=int(start_match.group(2)),
        end_col=column_str_to_int(end_match.group(1)),
        end_row=int(end_match.group(2)),
    )


def _format_range_address(start_col: int, start_row: int, end_col: int, end_row: int) -> str:
    """Build a bare (no sheet prefix) range address for a per-worksheet ``range(address=...)`` call."""
    return f"{column_int_to_str(start_col)}{start_row}:{column_int_to_str(end_col)}{end_row}"


