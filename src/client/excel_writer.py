def _session_header(session_id: str | None) -> dict[str, str]:
    return {"workbook-session-id": session_id} if session_id is not None else {}


@contextmanager
def workbook_session(client: GraphClient, drive_id: str, file_id: str) -> Iterator[str | None]:
    """Open an Excel workbook session for the duration of the ``with`` block.

    Yields the session id (for the caller to pass into :func:`resolve_worksheet`/
    :func:`write_table`), or ``None`` when the session couldn't be created — Graph still
    guarantees write persistence without one, so sessionless is a valid (if slower) fallback
    rather than an error (design spec §4). ``closeSession`` always runs in ``finally``,
    exceptions swallowed (v1 relied on a PHP destructor for this; a `finally` block is the
    equivalent here without the destructor timing pitfalls).
    """
    session_id = _create_session(client, drive_id, file_id)
    try:
        yield session_id
    finally:
        if session_id is not None:
            _close_session(client, drive_id, file_id, session_id)


def _create_session(client: GraphClient, drive_id: str, file_id: str) -> str | None:
    url = f"/drives/{drive_id}/items/{file_id}/workbook/createSession"
    try:
        response = client.post(
            url,
            json={"persistChanges": True},
            headers={"Prefer": "respond-async"},
            retry_transient_workbook=True,
        )
    except GraphClientError:
        logger.warning("The workbook session could not be created.")
        return None

    if response.status_code == 201:
        return response.json()["id"]
    if response.status_code == 202:
        return _poll_session_creation(client, response.headers.get("Location"))
    logger.warning("The workbook session could not be created.")
    return None


def _poll_session_creation(client: GraphClient, location: str | None) -> str | None:
    """Poll ``location`` (a 202 ``createSession``'s ``Location`` header) up to a deadline.

    Bounded to :data:`_SESSION_POLL_MAX_ATTEMPTS` (~120s at :data:`_SESSION_POLL_INTERVAL_SECONDS`
    intervals) so a session stuck "running" doesn't poll forever; a timed-out poll falls back to
    sessionless the same way any other session-creation failure does (design spec §4 — a session
    is a performance optimization only, never required for correctness).
    """
    if location:
        try:
            for _ in range(_SESSION_POLL_MAX_ATTEMPTS):
                body = client.get(location, absolute=True).json()
                status = body.get("status")
                if status == "running":
                    time.sleep(_SESSION_POLL_INTERVAL_SECONDS)
                    continue
                if status == "succeeded" and body.get("resourceLocation"):
                    result = client.get(body["resourceLocation"], absolute=True).json()
                    return result.get("id")
                break
        except GraphClientError:
            pass
    logger.warning("The workbook session could not be created.")
    return None


def _close_session(client: GraphClient, drive_id: str, file_id: str, session_id: str) -> None:
    url = f"/drives/{drive_id}/items/{file_id}/workbook/closeSession"
    try:
        client.post(url, headers=_session_header(session_id), retry_transient_workbook=True)
    except Exception:
        logger.debug("Failed to close workbook session %s; ignoring.", session_id, exc_info=True)


