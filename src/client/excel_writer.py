def _worksheet_base_url(drive_id: str, file_id: str, worksheet_id: str) -> str:
    # Worksheet ids contain `{}` (e.g. "{00000000-0001-0000-0000-000000000000}"), which must be
    # percent-encoded (-> %7B / %7D) to be a valid URL path segment.
    encoded_id = quote(worksheet_id, safe="")
    return f"/drives/{drive_id}/items/{file_id}/workbook/worksheets/{encoded_id}"


def _list_worksheets(client: GraphClient, drive_id: str, file_id: str, headers: dict[str, Any]) -> list[dict[str, Any]]:
    """Page through every worksheet in the workbook (``@odata.nextLink``, workbook-transient retries).

    Delegates to :meth:`GraphClient.get_paged` (its ``**request_kwargs`` passthrough is what makes
    ``retry_transient_workbook=True`` possible here) instead of hand-rolling the same pagination
    loop again (phase 8 audit).
    """
    url = f"/drives/{drive_id}/items/{file_id}/workbook/worksheets"
    return list(
        client.get_paged(
            url, params={"$select": WORKSHEET_LIST_SELECT}, headers=headers, retry_transient_workbook=True
        )
    )


def resolve_worksheet(
    client: GraphClient, drive_id: str, file_id: str, worksheet: Worksheet, session: str | None
) -> tuple[str, bool, str]:
    """Resolve ``worksheet`` to ``(worksheet_id, is_new, actual_name)``, creating/renaming as needed.

    Targeting (``Worksheet``'s ``id``/``position``/``name`` are validated mutually-exclusive-ish
    by the config model — see ``configuration.Worksheet``): ``id``/``position`` must match an
    existing sheet (:class:`~client.exceptions.WorksheetNotFoundError` otherwise, v1 parity — no
    create-by-id/position); a bare ``name`` creates the sheet when missing. Either way, a
    ``name`` that differs from the resolved sheet's actual name triggers a rename *before* the
    caller writes anything (v1 parity: "worksheet.id/position + worksheet.name" = "target this
    sheet, and also rename it").
    """
    headers = _session_header(session)
    worksheets = _list_worksheets(client, drive_id, file_id, headers)

    if worksheet.id is not None:
        match = _find_worksheet(worksheets, lambda item: item["id"] == worksheet.id)
        if match is None:
            raise WorksheetNotFoundError(f'Worksheet with id "{worksheet.id}" not found in the workbook.')
        worksheet_id, actual_name, is_new = match["id"], match["name"], False
    elif worksheet.position is not None:
        match = _find_worksheet(worksheets, lambda item: item["position"] == worksheet.position)
        if match is None:
            raise WorksheetNotFoundError(f'Worksheet at position {worksheet.position} not found in the workbook.')
        worksheet_id, actual_name, is_new = match["id"], match["name"], False
    else:
        # `configuration.Worksheet` requires at least one of id/name/position; having reached
        # here (no id, no position), `name` must be set.
        assert worksheet.name is not None
        match = _find_worksheet(worksheets, lambda item: item["name"] == worksheet.name)
        if match is not None:
            worksheet_id, actual_name, is_new = match["id"], match["name"], False
        else:
            created = _create_worksheet(client, drive_id, file_id, worksheet.name, headers)
            worksheet_id, actual_name, is_new = created["id"], created["name"], True

    if worksheet.name and not is_new and actual_name != worksheet.name:
        _rename_worksheet(client, drive_id, file_id, worksheet_id, worksheet.name, headers)
        actual_name = worksheet.name

    return worksheet_id, is_new, actual_name


def _find_worksheet(worksheets: list[dict[str, Any]], predicate) -> dict[str, Any] | None:
    return next((item for item in worksheets if predicate(item)), None)


def _create_worksheet(client: GraphClient, drive_id: str, file_id: str, name: str, headers: dict[str, Any]) -> dict[str, Any]:
    url = f"/drives/{drive_id}/items/{file_id}/workbook/worksheets/add"
    response = client.post(url, json={"name": name}, headers=headers, retry_transient_workbook=True)
    logger.info('New sheet "%s" created.', name)
    return response.json()


def _rename_worksheet(
    client: GraphClient, drive_id: str, file_id: str, worksheet_id: str, new_name: str, headers: dict[str, Any]
) -> None:
    url = _worksheet_base_url(drive_id, file_id, worksheet_id)
    client.patch(url, json={"name": new_name}, headers=headers, retry_transient_workbook=True)


def _read_header_row(
    client: GraphClient, drive_id: str, file_id: str, worksheet_id: str, headers: dict[str, Any]
) -> list[str]:
    """Read a worksheet's first-row cell values (as strings), via ``usedRange``'s row 0.

    Shared by :func:`_prepare_append` (decides whether an append target already has a header)
    and :func:`list_worksheets_with_headers` (the ``getWorksheets`` sync action's per-sheet
    ``header`` field) — both need the exact same raw cell values before applying their own,
    different, follow-up logic (a mismatch warning vs. v1's ASCII normalization).

    Graph still returns a one-cell row (``text: [[""]]``) for a genuinely empty worksheet rather
    than erroring, so this never raises for "no data yet" — callers see ``[""]``, not ``[]``, and
    decide for themselves what "empty" means for their purpose.
    """
    base_url = _worksheet_base_url(drive_id, file_id, worksheet_id)
    header_row = client.get(
        f"{base_url}/range/usedRange(valuesOnly=true)/row(row=0)",
        params={"$select": "address,text"},
        headers=headers,
        retry_transient_workbook=True,
    ).json()
    text_rows = header_row.get("text") or []
    return [str(cell) for cell in text_rows[0]] if text_rows else []


def list_worksheets(client: GraphClient, drive_id: str, file_id: str) -> list[dict[str, Any]]:
    """List a workbook's worksheets (``id``/``name``/``position``/``visibility``), position-sorted.

    Sessionless (sync actions never open a workbook session — v1 doesn't either). This is the
    lightweight half of :func:`list_worksheets_with_headers` (no per-sheet header read) — shared
    by the ``listWorksheets`` sync action (workbook/worksheet dropdown UX addition), which only
    needs enough to build a ``SelectElement`` per sheet, never the header row.
    """
    worksheets = _list_worksheets(client, drive_id, file_id, headers={})
    worksheets.sort(key=lambda item: item["position"])
    return worksheets


def list_worksheets_with_headers(client: GraphClient, drive_id: str, file_id: str) -> list[dict[str, Any]]:
    """List every worksheet in a workbook with its normalized header (``getWorksheets``, §5).

    Sessionless (sync actions never open a workbook session — v1 doesn't either) and
    position-sorted, matching v1's ``Api::getSheets`` output shape exactly (field names, ``"
    (hidden)"`` title suffix, ASCII-normalized ``header`` via :mod:`client.headers`). Built on top
    of :func:`list_worksheets` — the listing + sort is identical, this just adds the per-sheet
    header read.
    """
    worksheets = list_worksheets(client, drive_id, file_id)

    result: list[dict[str, Any]] = []
    for item in worksheets:
        header_cells = _read_header_row(client, drive_id, file_id, item["id"], headers={})
        visible = str(item.get("visibility", "")).lower() == "visible"
        name = item["name"]
        result.append(
            {
                "position": item["position"],
                "name": name,
                "title": name if visible else f"{name} (hidden)",
                "driveId": drive_id,
                "fileId": file_id,
                "worksheetId": item["id"],
                "visible": visible,
                "header": normalize_header_row(header_cells),
            }
        )
    return result


