"""Excel worksheet writer for keboola.wr-onedrive-v2 (mode=table_excel).

Design spec: ``docs/superpowers/specs/2026-08-17-wr-onedrive-v2-design.md`` §4 (Excel rows of the
capability table + "Excel session" mechanics) and §5 (Excel options). This is a port of
``keboola.wr-onedrive`` (v1, PHP)'s ``InsertRowsManager``/workbook-resolution semantics — v1
feature parity is an acceptance criterion, so the row-by-row write algorithm, header-skip rules,
and path-targeting forms below intentionally mirror v1's behavior rather than inventing new ones.

Three concerns live here, as module-level functions taking an injected
:class:`~client.graph_client.GraphClient` (same style as ``client.drives``/``client.uploader``):

- **Workbook resolution** (:func:`resolve_workbook`) — targets a workbook by ``driveId``+
  ``fileId``, a ``/root-relative`` path, a ``drive://``/``site://`` path, or an ``https://``
  sharing link; creates a minimal empty workbook when a path-mode target doesn't exist yet.
- **Session lifecycle** (:func:`workbook_session`) — a context manager wrapping Excel's
  ``createSession``/``closeSession`` dance, with 202-polling and a sessionless fallback (Graph
  guarantees persistence either way; a session is a performance optimization only).
- **Worksheet resolution + write** (:func:`resolve_worksheet`, :func:`write_table`) — finds/
  creates/renames the target sheet, then writes a CSV into it in batched ``range`` PATCHes,
  reproducing v1's overwrite (clear + write from A1) and append (usedRange-offset, header-skip)
  semantics, plus a third, non-v1 ``write_mode``: upsert (key-column matching, in-place row
  updates — see :func:`_write_upsert`).

Callers (plan Task 8's Excel-mode ``run()`` wiring) are expected to: call
:func:`resolve_workbook` once, open :func:`workbook_session` around the rest of the row, call
:func:`resolve_worksheet` inside it, then :func:`write_table`. Writes are always serialized (no
concurrency anywhere in this module) — Microsoft's own guidance for one workbook.
"""

