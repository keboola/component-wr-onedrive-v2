def write_table(
    client: GraphClient,
    drive_id: str,
    file_id: str,
    worksheet_id: str,
    csv_path: str,
    *,
    write_mode: WriteMode,
    key_columns: list[str] | None = None,
    batch_size: int,
    is_new_sheet: bool,
    session: str | None,
) -> bool:
    """Stream ``csv_path`` into the worksheet, batched ``batch_size`` rows per ``range`` PATCH.

    Returns ``False`` (touching nothing on the sheet) when ``csv_path`` has no header row at all
    (a completely empty CSV) — the caller logs ``Ignored empty CSV file "<name>".`` and exits 0,
    v1 parity. Returns ``True`` otherwise.

    ``write_mode='overwrite'``: clears the whole sheet first (unless it was just created, in
    which case there's nothing to clear) and writes from A1, header included.

    ``write_mode='append'``: offsets from the sheet's ``usedRange`` — an existing non-empty
    header means the CSV's own header row is skipped (with a warning if the two headers differ,
    v1 parity — the warning is informational only, it never blocks the append); an empty sheet
    (including a freshly created one) writes the header too, same as overwrite.

    ``write_mode='upsert'``: matches existing rows to CSV rows by ``key_columns`` (required
    non-empty — enforced by ``configuration.RowConfig``, not re-checked here) and updates them in
    place, appending everything else after the last used row; see :func:`_write_upsert` for the
    algorithm. An empty (or freshly created) sheet behaves like ``overwrite``.

    For ``overwrite``/``append``, the column count is fixed from the CSV's header for every batch
    (short rows padded with empty strings, long rows truncated) — Excel's range PATCH requires a
    rectangular ``values`` array. Any cell whose value starts with ``=`` is prefixed with ``'``
    (v1 parity — formula injection safety; Excel treats a leading ``'`` as "force literal text").
    ``upsert`` applies the same padding/escaping to every row it writes (via the same
    :func:`_prepare_row` helper).

    If the workbook session expires mid-write (a workbook call 404s while a session header is
    set), the session is recreated once and the same batch is retried before giving up (the same
    guarantee ``overwrite``/``append`` already had, via :func:`_patch_batch`).
    """
    with open(csv_path, newline="", encoding="utf-8") as csv_file:
        reader = csv.reader(csv_file)
        header = next(reader, None)
        if header is None:
            return False
        header_len = len(header)

        if write_mode == WriteMode.UPSERT:
            _write_upsert(
                client,
                drive_id,
                file_id,
                worksheet_id,
                header,
                reader,
                key_columns or [],
                batch_size,
                is_new_sheet,
                _session_header(session),
                session,
            )
            return True

        if write_mode == WriteMode.APPEND:
            start_row, start_col, include_header = _prepare_append(
                client, drive_id, file_id, worksheet_id, is_new_sheet, header, _session_header(session)
            )
        else:
            start_row, start_col, include_header = _prepare_overwrite(
                client, drive_id, file_id, worksheet_id, is_new_sheet, _session_header(session)
            )

        rows = _rows_to_write(header, reader, include_header)
        session_id = session
        for batch in _batched(rows, batch_size):
            padded_batch = [_prepare_row(row, header_len) for row in batch]
            session_id = _patch_batch(
                client,
                drive_id,
                file_id,
                worksheet_id,
                start_col,
                start_row,
                header_len,
                padded_batch,
                session_id,
            )
            start_row += len(padded_batch)

    return True


def _prepare_overwrite(
    client: GraphClient, drive_id: str, file_id: str, worksheet_id: str, is_new_sheet: bool, headers: dict[str, Any]
) -> tuple[int, int, bool]:
    if not is_new_sheet:
        url = f"{_worksheet_base_url(drive_id, file_id, worksheet_id)}/range/clear"
        client.post(url, json={"applyTo": "all"}, headers=headers, retry_transient_workbook=True)
    return 1, 1, True


def _prepare_append(
    client: GraphClient,
    drive_id: str,
    file_id: str,
    worksheet_id: str,
    is_new_sheet: bool,
    csv_header: list[str],
    headers: dict[str, Any],
) -> tuple[int, int, bool]:
    if is_new_sheet:
        logger.info("Sheet is empty.")
        return 1, 1, True

    base_url = _worksheet_base_url(drive_id, file_id, worksheet_id)
    used_range = client.get(
        f"{base_url}/range/usedRange(valuesOnly=true)", params={"$select": "address"}, headers=headers,
        retry_transient_workbook=True,
    ).json()
    range_info = parse_range_address(used_range["address"])

    existing_header = _read_header_row(client, drive_id, file_id, worksheet_id, headers)

    if not any(cell.strip() for cell in existing_header):
        logger.info("Sheet is empty.")
        return 1, 1, True

    if existing_header != csv_header:
        logger.warning("Headers mismatch. Ignored new header: %s", ", ".join(csv_header))

    return range_info.end_row + 1, range_info.start_col, False


def _rows_to_write(header: list[str], reader: Iterator[list[str]], include_header: bool) -> Iterator[list[str]]:
    if include_header:
        yield header
    yield from reader


def _batched(rows: Iterator[list[str]], size: int) -> Iterator[list[list[str]]]:
    iterator = iter(rows)
    while True:
        batch = list(itertools.islice(iterator, size))
        if not batch:
            return
        yield batch


def _prepare_row(row: list[str], header_len: int) -> list[str]:
    padded = list(row[:header_len]) + [""] * max(0, header_len - len(row))
    return [_escape_formula(str(cell)) for cell in padded]


def _escape_formula(value: str) -> str:
    return f"'{value}" if value.startswith("=") else value


def _patch_batch(
    client: GraphClient,
    drive_id: str,
    file_id: str,
    worksheet_id: str,
    start_col: int,
    start_row: int,
    header_len: int,
    batch: list[list[str]],
    session_id: str | None,
) -> str | None:
    end_row = start_row + len(batch) - 1
    end_col = start_col + header_len - 1
    address = _format_range_address(start_col, start_row, end_col, end_row)
    url = f"{_worksheet_base_url(drive_id, file_id, worksheet_id)}/range(address='{address}')"

    try:
        client.patch(
            url, json={"values": batch}, headers=_session_header(session_id), retry_transient_workbook=True
        )
    except GraphNotFoundError:
        if session_id is None:
            raise
        logger.info("Workbook session expired mid-write; recreating it once and retrying the batch.")
        session_id = _create_session(client, drive_id, file_id)
        client.patch(
            url, json={"values": batch}, headers=_session_header(session_id), retry_transient_workbook=True
        )

    logger.info("Inserted %d rows.", len(batch))
    return session_id


